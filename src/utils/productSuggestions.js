/**
 * Get fuzzy matching suggestions from both the active inventory and the popular catalog.
 * Searches across name, model, brand, color, ram, storage.
 */
export function getProductSuggestions(query = '', inventory = [], limit = 8) {
  const cleanQ = (query || '').toLowerCase().trim();
  if (!cleanQ || cleanQ.length < 2) return [];

  const tokens = cleanQ.split(/\s+/).filter(Boolean);

  // Combine items from active inventory + popular catalog
  const allCandidates = [];
  const seenNames = new Set();

  // 1. Existing inventory items (highest priority)
  if (Array.isArray(inventory)) {
    inventory.forEach(item => {
      if (item?.name && !seenNames.has(item.name.toLowerCase())) {
        seenNames.add(item.name.toLowerCase());
        allCandidates.push({
          source: 'inventory',
          name: item.name,
          brand: item.brand || '',
          category: item.category || 'New Mobiles',
          model: item.model || '',
          ram: item.ram || '',
          storage: item.storage || '',
          color: item.color || '',
          hsn: item.hsn || '851712',
          gstRate: item.gstRate || 18,
          suggestedBuy: item.buyPrice || 0,
          suggestedSell: item.sellPrice || 0,
          stock: item.stock
        });
      }
    });
  }

  // 2. Popular catalog items
  POPULAR_CATALOG.forEach(catItem => {
    if (!seenNames.has(catItem.name.toLowerCase())) {
      seenNames.add(catItem.name.toLowerCase());
      allCandidates.push({
        source: 'catalog',
        ...catItem
      });
    }
  });

  // Filter candidates matching all tokens
  const scored = [];

  for (const item of allCandidates) {
    const searchString = [
      item.name || '',
      item.model || '',
      item.brand || '',
      item.ram || '',
      item.storage || '',
      item.color || '',
      item.category || ''
    ].join(' ').toLowerCase();

    // Check if every token is present
    const matchesAll = tokens.every(tok => searchString.includes(tok));
    if (matchesAll) {
      let score = 0;
      const lowerName = item.name.toLowerCase();

      // Exact prefix match on product name gets massive bonus
      if (lowerName.startsWith(cleanQ)) score += 100;
      // Word boundary match
      if (lowerName.includes(` ${cleanQ}`)) score += 50;
      // Exact model match
      if (item.model && item.model.toLowerCase().includes(cleanQ)) score += 40;
      // Inventory items preferred
      if (item.source === 'inventory') score += 15;

      scored.push({ item, score });
    }
  }

  // Sort by score desc, then by name length asc (more concise matches first)
  scored.sort((a, b) => b.score - a.score || a.item.name.length - b.item.name.length);

  return scored.slice(0, limit).map(s => s.item);
}
